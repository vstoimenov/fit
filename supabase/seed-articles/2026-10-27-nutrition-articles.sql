## Две числа, които да запомниш

Европейският орган по безопасност на храните (EFSA) препоръчва за възрастни поне **0,83 g белтък на килограм** телесно тегло на ден. Това е минимумът за здравето. За жени, които тренират редовно, Международното дружество по спортно хранене (ISSN) препоръчва **1,4–2,0 g на килограм**, за да изграждат и пазят мускули.

