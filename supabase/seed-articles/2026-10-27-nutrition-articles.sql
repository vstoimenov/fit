## Три мита, които спират жените

**„От протеина ще стана огромна.“** Жените трупат мускули по-бавно от мъжете заради по-ниския тестостерон. Протеинът и тренировките правят тялото стегнато и силно, а не масивно.

**„Трябват ми шейкове.“** Не са задължителни. Храната е на първо място. Шейкът е удобен вариант за дни, в които нямаш време, и толкова.

**„Много белтък уврежда бъбреците.“** При здрави хора количествата по-горе не са опасни. Ако имаш бъбречно заболяване, количеството се определя от лекаря ти.

> **Започни с една стъпка.** Тази седмица сложи белтък в закуската. Само в закуската. Следващата седмица продължи с обяда.

