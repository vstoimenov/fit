## 1. Започни с един навик, не със седем

Изследване на University College London проследява 96 души, които всеки ден повтарят едно ново действие, например чаша вода със закуската. Средно им трябват **66 дни**, докато действието стане автоматично. При някои стават 18, при други над 200. Пропуснат ден не връща човека в началото.

> Избери **един** навик от списъка по-долу. Само един. Когато стане естествен, добави следващия.

## 2. Мисли в чинии, не в грамове

Не ти трябва кантар. Погледни чинията и я раздели наум. Тази проста карта идва от Харвардската школа по обществено здраве и работи за обяд, вечеря и дори за кутията, която носиш на работа.

- **Половината: зеленчуци и плодове.** Колкото повече цветове, толкова по-добре. Замразените също се броят.
- **Четвърт: белтък.** Яйца, риба, пилешко, боб, леща, извара.
- **Четвърт: пълнозърнести.** Кафяв ориз, пълнозърнест хляб, овесени ядки, картофи.

## 3. Белтък на всяко хранене

Когато закуската е само кафе и кроасан, в 11 часа вече търсиш нещо сладко. Белтъкът засища по-дълго и помага на мускулите да се възстановяват след тренировка. Не е нужно да го мериш. Просто провери: има ли белтък в това, което ям сега?

Бързи варианти за сутрин: кисело мляко с ядки, две яйца на филия, извара с плод.

## 4. 20 минути в неделя

Най-трудният момент е 19:00 в делничен ден, когато си гладна, уморена и нищо не е готово. Двадесет минути в неделя решават половината седмица.

**Неделният списък**

- Измий и нарежи зеленчуци за 3 дни в кутии.
- Свари 6 яйца.
- Сготви голяма тава с пилешко или зеленчуци на фурна.
- Свари една тенджера ориз, киноа или леща.

## 5. Закачи новото за старото

Нов навик се хваща по-лесно, когато го свържеш с нещо, което вече правиш всеки ден. Формулата е проста: *след като направя Х, ще направя У.*

- След като пусна кафемашината, изпивам чаша вода.
- След като сложа децата да вечерят, слагам и моята чиния. Със зеленчуци.
- След като разопаковам пазара, нарязвам плодовете и ги слагам на видно място.

## 6. Смени, не забранявай

Забраната прави храната по-желана. Вместо да махаш, смени едно нещо с подобно, което те засища повече.

| Вместо | Опитай |
| --- | --- |
| Сок от кутия | **Вода с лимон или цял плод** |
| Бяла франзела | **Пълнозърнест хляб** |
| Плодово кисело мляко | **Обикновено кисело мляко с мед и плод** |
| Пакет чипс пред телевизора | **Шепа ядки в купичка** |
| Втора чаша кафе в 16:00 | **Разходка за 10 минути** |

## 7. Правилото 80/20

Ако през повечето време се храниш добре, едно парче торта на рождения ден на детето не разваля нищо. Седмицата се гради от навиците, а не от едно хранене. Ако хапнеш нещо „не по плана“, това не е провал и не е повод да започнеш отново от понеделник.

